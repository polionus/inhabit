export const PRESET_BY_ID: Record<BuiltInPresetId, ThemePreset> = {
  indigo: INDIGO_PRESET,
  botanical: BOTANICAL_PRESET,
  terracotta: TERRACOTTA_PRESET,
  ocean: OCEAN_PRESET,
  rose: ROSE_PRESET,
  editorial: EDITORIAL_PRESET,
};

export function getPreset(id: string | undefined, extraPresets: ThemePreset[] = []): ThemePreset {
  if (id) {
    const custom = extraPresets.find((p) => p.id === id);
    if (custom) return custom;
    if (id in PRESET_BY_ID) return PRESET_BY_ID[id as BuiltInPresetId];
  }
  return INDIGO_PRESET;
}
